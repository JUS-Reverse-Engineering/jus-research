#!/usr/bin/env python3
"""Validate docs/research/gamefaqs-movesets/*.json against SCHEMA.md and write README.md.

Usage: python3 scripts/analysis/gamefaqs_movesets_index.py [--write]
Exit 1 on any schema problem. The README lists every extract and every
chr_b character with no guide (from docs/research/chr_b-Complete-Mapping.md).
"""
import glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DIR = os.path.join(ROOT, "docs/research/gamefaqs-movesets")
MAP = os.path.join(ROOT, "docs/research/chr_b-Complete-Mapping.md")
TOP = {"character", "series", "chr_b", "source", "kit_type", "koma", "moves", "unresolved"}
MOVE = {"input", "description", "quote"}
KOMA = {"size", "role"}
INPUTS = {"B", "side B", "up B", "down B", "air B", "Y", "side Y", "up Y", "down Y",
          "air Y", "select", "B string", "other"}

def chrb_table():
    rows = {}
    for line in open(MAP, encoding="utf-8"):
        m = re.match(r"\|\s*(\d+)\s*\|\s*(\w+)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|", line)
        if m:
            rows[int(m.group(1))] = (m.group(3), m.group(4))
    return rows

def check(path, data, errs):
    miss = TOP - set(data)
    if miss: errs.append(f"{path}: missing top keys {sorted(miss)}")
    for i, k in enumerate(data.get("koma", [])):
        if KOMA - set(k): errs.append(f"{path}: koma[{i}] missing {sorted(KOMA - set(k))}")
    for i, mv in enumerate(data.get("moves", [])):
        if MOVE - set(mv): errs.append(f"{path}: moves[{i}] missing {sorted(MOVE - set(mv))}")
        if mv.get("input") not in INPUTS:
            errs.append(f"{path}: moves[{i}] input {mv.get('input')!r} not in schema list")
    if data.get("chr_b") is not None and not isinstance(data["chr_b"], int):
        errs.append(f"{path}: chr_b must be int or null")

def main():
    write = "--write" in sys.argv
    table = chrb_table()
    errs, rows, covered = [], [], set()
    for path in sorted(glob.glob(os.path.join(DIR, "*.json"))):
        try:
            data = json.load(open(path, encoding="utf-8"))
        except Exception as e:
            errs.append(f"{path}: not valid JSON ({e})"); continue
        check(path, data, errs)
        cb = data.get("chr_b")
        if cb is not None:
            covered.add(cb)
            if cb in table and table[cb][0].lower().split()[0] not in data.get("character", "").lower():
                errs.append(f"{path}: chr_b {cb} is {table[cb][0]!r} in the mapping, file says {data.get('character')!r}")
        rows.append((data.get("character", "?"), cb, data.get("kit_type", "?"),
                     len(data.get("koma", [])), len(data.get("moves", [])),
                     len(data.get("unresolved", [])), os.path.basename(path),
                     (data.get("source") or {}).get("file", "?")))
    for e in errs: print("ERROR", e)
    print(f"{len(rows)} extracts, {len(errs)} errors")
    if errs and not write: sys.exit(1)
    if write:
        out = ["# GameFAQs moveset extracts", "",
               "Generated by `scripts/analysis/gamefaqs_movesets_index.py --write`; do not edit by hand.",
               "Schema and trust rules: `SCHEMA.md`. Corpus: `docs/research/sources/gamefaqs.md`.",
               "Extraction tracker item: `jus-6ckd`. These are player-written guides, testimony not measurement.", "",
               "| character | chr_b | kit | koma | moves | unresolved | file | source |", "|---|---|---|---|---|---|---|---|"]
        for r in sorted(rows, key=lambda r: (r[1] if r[1] is not None else 999, r[0])):
            out.append("| " + " | ".join("" if v is None else f"`{v}`" if i in (6, 7) else str(v) for i, v in enumerate(r)) + " |")
        missing = [(cb, n, s) for cb, (n, s) in sorted(table.items()) if cb not in covered and s != "Debug"]
        out += ["", "## Playable characters with no guide extract", "",
                "| chr_b | character | series |", "|---|---|---|"]
        out += [f"| {cb} | {n} | {s} |" for cb, n, s in missing]
        open(os.path.join(DIR, "README.md"), "w", encoding="utf-8").write("\n".join(out) + "\n")
        print("wrote README.md;", len(missing), "characters without a guide")
    sys.exit(1 if errs else 0)

if __name__ == "__main__":
    main()
