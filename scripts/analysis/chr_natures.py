#!/usr/bin/env python3
"""Per-character nature bytes of chr_b.bin, as a committed table: the base
nature (byte 0) and the B and C slot natures for each koma size 4-8.

Output: docs/rebuild/chr-natures.json (+ .md with the rule and the cites). The
exporter (scripts/kit/export_kit.py) reads the JSON, never the binary.

Source: jus_files/ripped_jus_files/bin/chr_b.bin, 60 bytes per character (the
chr_b index is the record index). The byte map is the one dump_koma.py's
resolve_natures reads (chr_b[abilityId] + 0x00 for byte 0).

The rule (static; arm9 disassembly, E3b selectors and 0x15 agree):
  - byte 0 is the base nature A-source (arm9 0x02077C7C writes it to char+0x13);
  - for koma size s in 4..8 the set B nature is byte 0x10+(s-4)*4+2 (write at
    0x02077C84 to char+0x14) and the C nature is byte 0x10+(s-4)*4+3 (write at
    0x02077C8C to char+0x15). Init 0x02077C0C computes the offsets.
  - the panel override of A (arm9 0x02076FA4, from koma[0xB]>>4 when not 3) changes
    char+0x13 only; B and C never see it.

Usage:
    python3 scripts/analysis/chr_natures.py build   # write the .json and .md
    python3 scripts/analysis/chr_natures.py check   # exit 0 = committed files are fresh
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
CHR_B = REPO / "jus_files" / "ripped_jus_files" / "bin" / "chr_b.bin"
OUT = REPO / "docs" / "rebuild" / "chr-natures.json"
OUT_MD = REPO / "docs" / "rebuild" / "chr-natures.md"

STRIDE = 60
SIZES = (4, 5, 6, 7, 8)
SLOT_DELTA = {"B": 2, "C": 3}
PINNED = (("Eve", 37), ("Kakashi", 23), ("Yusuke", 32))
# Provenance: a capture measured the set-hit slots of these chr_b indexes. The exporter reads the
# file named here (its per_hit_record rows) for the grade of nature_slot; nothing else.
CAPTURES = (
    {"chr_b": 37, "file": "docs/research/feel-captures/2026-10-12-eve-mash/nature.json",
     "cite": "E3b capture, README Goal B: selectors 0x60 (B), 0x81 and 0xa4 (C); nature KNOWLEDGE"},
    {"chr_b": 38, "file": "docs/research/feel-captures/2026-10-14-train-specials/nature.json",
     "cite": "TRX capture, saved EL dumps: selectors 0x41 (B, Rail Gun), 0x80 (C, rec14 and rec18), 0 (A, rec15); "
             "P1 M+0x175 = 0 (POWER)"},
)


def slot_offset(size: int, slot: str) -> int:
    """Byte offset in a chr_b record of the nature for koma size `size` and slot B or C."""
    if size not in SIZES:
        raise ValueError(f"koma size must be 4..8, got {size}")
    return 0x10 + (size - 4) * 4 + SLOT_DELTA[slot]


def char_row(index: int, rec: bytes) -> dict:
    return {
        "chr_b": index,
        "base": rec[0],
        "by_size": {str(s): {slot: rec[slot_offset(s, slot)] for slot in ("B", "C")} for s in SIZES},
        "raw": rec.hex(),
    }


def build_table(data: bytes) -> dict:
    if len(data) % STRIDE:
        raise ValueError(f"chr_b is {len(data)} bytes, not a multiple of {STRIDE}")
    chars = [char_row(i, data[i * STRIDE:(i + 1) * STRIDE]) for i in range(len(data) // STRIDE)]
    return {
        "_schema": "docs/rebuild/chr-natures.md",
        "_generated_by": "python3 scripts/analysis/chr_natures.py build",
        "source": "jus_files/ripped_jus_files/bin/chr_b.bin",
        "stride": STRIDE,
        "sizes": list(SIZES),
        "captured": [dict(c) for c in CAPTURES],
        "characters": chars,
    }


def build() -> dict:
    if not CHR_B.exists():
        raise SystemExit(f"chr_natures: {CHR_B.relative_to(REPO)} is missing; symlink jus_files")
    return build_table(CHR_B.read_bytes())


def dump(table: dict) -> str:
    return json.dumps(table, indent=1, sort_keys=True) + "\n"


def render_md(table: dict) -> str:
    by = {c["chr_b"]: c for c in table["characters"]}
    out = [
        "# chr-natures (chr_b.bin nature bytes)",
        "",
        "Generated by `python3 scripts/analysis/chr_natures.py build` from "
        "jus_files/ripped_jus_files/bin/chr_b.bin (stride 60, record index = chr_b). "
        "Committed as `docs/rebuild/chr-natures.json`. Enum: 0 POWER, 1 KNOWLEDGE, 2 LAUGHTER, "
        "3 NEUTRAL (no nature; the exporter writes null).",
        "",
        "## Rule (static)",
        "",
        "- `base` = byte 0. Battle init 0x02077C0C writes it to char+0x13 (strb at 0x02077C7C).",
        "- Koma size s (4..8): B = byte `0x10+(s-4)*4+2` (write 0x02077C84 to char+0x14); "
        "C = byte `0x10+(s-4)*4+3` (write 0x02077C8C to char+0x15).",
        "- The panel override of A (0x02076FA4, from koma[0xB]>>4 when not 3) changes char+0x13 "
        "only. B and C never see the panel.",
        "- Slot selection for a hit is from its KB mask (arm9 table T18 at 0x0209FDC4: mask bit 10 "
        "(0x400) -> selector bit 6 -> B, bit 11 (0x800) -> selector bit 7 -> C; neither -> A). When "
        "both 0x400 and 0x800 are set, B wins (no KB record in docs/rebuild/knockback-table.json has "
        "both). The exporter does that, not this table.",
        "- The `captured` list names the captures of set-hit slots (Eve chr 37, E3b; Train chr 38, TRX), so the "
        "exporter can grade those slots measured.",
        "",
        "The arm9 cites are a static trace (a Sonnet pass over the disassembly). The E3b "
        "selectors and the 0x15 readings agree (docs/research/feel-captures/2026-10-12-eve-mash/"
        "README.md Goal B).",
        "",
        "## Pinned rows",
        "",
        "| name | chr_b | base | size 4 B/C | size 5 B/C | size 6 B/C |",
        "|---|---|---|---|---|---|",
    ]
    for name, idx in PINNED:
        c = by[idx]
        cells = [f"{c['by_size'][s]['B']}/{c['by_size'][s]['C']}" for s in ("4", "5", "6")]
        out.append(f"| {name} | {idx} | {c['base']} | " + " | ".join(cells) + " |")
    out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("build", help="write docs/rebuild/chr-natures.json and .md")
    sub.add_parser("check", help="exit 0 iff the committed files equal a fresh build")
    a = ap.parse_args(argv)
    table = build()
    if a.cmd == "build":
        OUT.write_text(dump(table), encoding="utf-8")
        OUT_MD.write_text(render_md(table), encoding="utf-8")
        print(f"wrote {OUT.relative_to(REPO)} and {OUT_MD.relative_to(REPO)}")
        return 0
    fresh = OUT.exists() and OUT.read_text(encoding="utf-8") == dump(table) \
        and OUT_MD.exists() and OUT_MD.read_text(encoding="utf-8") == render_md(table)
    print("fresh" if fresh else "STALE: run build")
    return 0 if fresh else 1


if __name__ == "__main__":
    sys.exit(main())
