#!/usr/bin/env python3
"""ARM7 sound-channel recorder (j6mat): a second GDB client on the melonDS ARM7 stub records the NitroSDK sound driver's channel
allocation, hardware start, setting updates, stop writes and end observations, each at the instruction that performs it.

ARM7 facts (arm7.bin loads at 0x02380000; its first autoload block runs at 0x037F8000 from file offset 0x1B0, so a runtime PC A is
file offset A - 0x037F8000 + 0x1B0). Channel records C[ch] = 0x03808AA8 + 0x54*ch (u8 +0 hardware channel, +3 flags, +0x22
priority, +0x48 callback, +0x4C callback argument = owning track), players P[p] = 0x03808FE8 + 0x24*p (u8 +1 player id), tracks
T[t] = 0x03809228 + 0x40*t. All are ARM7-private WRAM: only an ARM7 client reads them.

  0x038021C4  sequence player start (push): r0 = player, r1 = sequence base, r2 = offset, r3 = bank.
  0x038013D0  note-channel link `str r4,[r8,#0x3c]`: r4 = C, r8 = T, r7 = P; the allocation of hardware channel u8[C] to track T
              of player u8[P+1] has succeeded.
  0x037FF298  PCM channel setup (push): r0 = channel, r1 = sample address, r2 = format, r3 = repeat; stack +0..+0x14 = loop
              point, length, volume, divider, timer period, pan.
  0x038006C8  `ldrb r0,[r4,#3]` right after the driver's start write `strbne r2,[r0,#0x403]` (0x038006C4): r5 = channel, r4 = C;
              a start happened when u8[C+3] bit 3 (the pending setup/start action) is set. The row reads the channel's SOUNDCNT
              (0x04000400 + 16*ch), the mixer SOUNDCNT 0x04000500 and SOUNDBIAS 0x04000504 after the start.
  0x037FF068 / 0x037FF080 / 0x037FEFEC  timer / volume / pan update of channel r0 to value r1 (volume divider r2).
  0x037FF124  stop write `str r2,[ip]`: ip = channel SOUNDCNT, r2 = the value with bit 31 cleared; a stop when the old CNT has
              bit 31 set.
  0x03800294  natural-end observation: hardware channel r4 (record r5) was found inactive; the physical end happened before.
  0x03801654  sequence channel callback (push): r0 = C, r1 = reason (1 after a natural end, 0 steal/forced), r2 = T.

Every row is `A7xx gfc=<ARM9 frame counter read from main RAM at that instruction>`. GDB's ARM7 breakpoints are hardware
breakpoints in melonDS (no code bytes change); the reads are main RAM, ARM7 WRAM and SPU registers, whose reads have no side
effects (SPU::Read8/16/32 return the stored registers). Timers are not read: a timer register read catches the timer up.
"""
import re
from collections import namedtuple

GFC = 0x020A0F10
SHARED_PTR = 0x020ACAE0            # ARM9 word -> SNDSharedWork (channelStatus at +8, player p tickCounter at +0x40 + 0x24*p)
CH_BASE, CH_SIZE = 0x03808AA8, 0x54
P_BASE, P_SIZE = 0x03808FE8, 0x24
T_BASE, T_SIZE = 0x03809228, 0x40

SITES = {   # name: (pc, opcode word in arm7.bin)
    "player_start": (0x038021C4, 0xE92D43F0),
    "link": (0x038013D0, 0xE588403C),
    "pcm_setup": (0x037FF298, 0xE92D41F0),
    "started": (0x038006C8, 0xE5D40003),
    "set_timer": (0x037FF068, 0xE2611801),
    "set_volume": (0x037FF080, 0xE92D4030),
    "set_pan": (0x037FEFEC, 0xE92D4010),
    "stop_write": (0x037FF124, 0xE58C2000),
    "end_observed": (0x03800294, 0xE5953048),
    "callback": (0x03801654, 0xE92D4030),
}

G = "*(unsigned int*)0x%08X" % GFC


def _bp(pc, body):
    return "break *0x%08X\ncommands\n  silent\n%s  continue\nend\n" % (pc, body)


def generate(port=3334):
    """The ARM7 client script. It prints each site's opcode word read from ARM7 memory first (A7OP), so a relocated or different
    image is refused by the decoder rather than recorded."""
    s = ["# GENERATED by scripts/gdb/snd_arm7.py; do not edit.", "set pagination off", "set confirm off",
         "set logging overwrite off", "set logging enabled on", "handle SIGILL stop nopass noprint",
         "target remote localhost:%d" % port]
    for name, (pc, _op) in SITES.items():
        s.append('printf "A7OP gfc=%%d site=%s pc=0x%%x op=0x%%x\\n", %s, 0x%08X, *(unsigned int*)0x%08X' % (name, G, pc, pc))
    s.append(_bp(SITES["player_start"][0],
                 '  printf "A7PS gfc=%%d player=%%d seqbase=0x%%x off=0x%%x bank=0x%%x\\n", %s, $r0, $r1, $r2, $r3\n' % G))
    s.append(_bp(SITES["link"][0],
                 '  printf "A7AL gfc=%%d C=0x%%x ch=%%d T=0x%%x P=0x%%x player=%%d prio=%%d r5=0x%%x r6=0x%%x cb=0x%%x arg=0x%%x\\n", %s, '
                 '$r4, *(unsigned char*)$r4, $r8, $r7, *(unsigned char*)($r7 + 1), *(unsigned char*)($r4 + 0x22), $r5, $r6, '
                 '*(unsigned int*)($r4 + 0x48), *(unsigned int*)($r4 + 0x4c)\n' % G))
    s.append(_bp(SITES["pcm_setup"][0],
                 '  printf "A7PC gfc=%%d ch=%%d sad=0x%%x fmt=%%d rep=%%d pnt=0x%%x len=0x%%x vol=%%d div=%%d tmr=%%d pan=%%d\\n", %s, '
                 '$r0, $r1, $r2, $r3, *(unsigned int*)$sp, *(unsigned int*)($sp + 4), *(unsigned int*)($sp + 8), '
                 '*(unsigned int*)($sp + 12), *(unsigned int*)($sp + 16), *(unsigned int*)($sp + 20)\n' % G))
    s.append(_bp(SITES["started"][0],
                 '  if (*(unsigned char*)($r4 + 3)) & 8\n'
                 '    printf "A7ST gfc=%%d ch=%%d C=0x%%x flags=0x%%x cnt=0x%%x mix=0x%%x bias=0x%%x status=0x%%x\\n", %s, $r5, $r4, '
                 '*(unsigned char*)($r4 + 3), *(unsigned int*)(0x04000400 + 16 * $r5), *(unsigned short*)0x04000500, '
                 '*(unsigned short*)0x04000504, *(unsigned short*)(*(unsigned int*)0x%08X + 8)\n  end\n' % (G, SHARED_PTR)))
    for name, tag in (("set_timer", "A7UT"), ("set_volume", "A7UV"), ("set_pan", "A7UP")):
        s.append(_bp(SITES[name][0], '  printf "%s gfc=%%d ch=%%d value=%%d div=%%d\\n", %s, $r0, $r1, $r2\n' % (tag, G)))
    s.append(_bp(SITES["stop_write"][0],
                 '  printf "A7SW gfc=%%d ch=%%d old=0x%%x new=0x%%x\\n", %s, ($r12 - 0x04000400) / 16, *(unsigned int*)$r12, $r2\n' % G))
    s.append(_bp(SITES["end_observed"][0], '  printf "A7NE gfc=%%d ch=%%d C=0x%%x\\n", %s, $r4, $r5\n' % G))
    s.append(_bp(SITES["callback"][0], '  printf "A7CB gfc=%%d C=0x%%x ch=%%d reason=%%d T=0x%%x\\n", %s, $r0, *(unsigned char*)$r0, $r1, $r2\n' % G))
    s.append('printf "PROBE_ARMED\\n"\ncontinue\n')
    return "\n".join(s) + "\n"


Row = namedtuple("Row", "line tag gfc kv")
ROW = re.compile(r"(A7[A-Z]{2}) gfc=(\d+)(.*)")
KV = re.compile(r"(\w+)=(\S*)")


def _num(v):
    return int(v, 16) if re.fullmatch(r"0x[0-9a-fA-F]+", v) else int(v) if re.fullmatch(r"-?\d+", v) else v


def parse(lines):
    out = []
    for i, ln in enumerate(lines):
        m = ROW.match(ln)
        if m:
            out.append(Row(i, m[1], int(m[2]), {k: _num(v) for k, v in KV.findall(m[3])}))
    return out


def window(lines, first, last):
    """The ARM7 rows of one native capture whose frame rows read game frame counters `first` and `last`: the A7OP guard rows, then
    the rows after the capture's state reload up to the last frame. The byte span recorded around the capture also holds the tail of
    the pre-reload run, whose counters overlap the capture's, so the reload is found as the last decrease of the counter, never by
    value. The first post-reload rows read `first - 1` (the ARM7 runs the frame before the first frame row). Raises ValueError when
    no reload boundary is visible and the rows do not start at the capture."""
    guards = [ln for ln in lines if ln.startswith("A7OP ")]
    rows = [(i, int(m[2])) for i, ln in enumerate(lines) for m in [ROW.match(ln)] if m and m[1] != "A7OP"]
    if not rows:
        raise ValueError("no ARM7 rows")
    k = max((j for j in range(1, len(rows)) if rows[j][1] < rows[j - 1][1]), default=0)
    if rows[k][1] < first - 1 or rows[k][1] > first:
        raise ValueError("the ARM7 rows after the reload start at gfc %d, the capture at %d" % (rows[k][1], first))
    end = next((i for i, g in rows[k:] if g > last), len(lines))
    return guards + lines[rows[k][0]:end]


def _cnt(v):
    """SOUNDxCNT fields (GBATEK): volume 0..6, divider 8..9, hold 15, pan 16..22, repeat 27..28, format 29..30, start 31."""
    return {"volume": v & 0x7F, "divider": (v >> 8) & 3, "hold": (v >> 15) & 1, "pan": (v >> 16) & 0x7F,
            "repeat": (v >> 27) & 3, "format": (v >> 29) & 3, "start": v >> 31}


def voices(rows):
    """Per hardware channel, one voice per start: its allocation (player, track) when the driver linked it, the PCM setup, the start
    with the post-start channel and mixer registers, setting updates while it runs, and its end, kept apart by kind:
    `stop_write` (a driver write clearing bit 31 of an active channel, at that instruction), `end_observed` (the driver found the
    channel inactive: the hardware ended it earlier, bounded by the previous row of that voice) and `callback` (the driver unlinked it).
    Refusals: opcode_mismatch (an A7OP word differs from arm7.bin), opcode_unguarded (a site has no A7OP row: the client prints them
    when it arms, so a capture window cut from the log carries them in front), start_unallocated (a start with no link of that
    channel since its previous voice)."""
    missing, out, live, alloc, setup = [], [], {}, {}, {}
    guarded = {r.kv.get("site") for r in rows if r.tag == "A7OP"}
    for site in SITES:
        if site not in guarded:
            missing.append({"kind": "opcode_unguarded", "line": None, "detail": "no A7OP row for site %s" % site})
    for r in rows:
        if r.tag == "A7OP":
            want = SITES.get(r.kv.get("site"))
            if want is None or (r.kv.get("pc"), r.kv.get("op")) != want:
                missing.append({"kind": "opcode_mismatch", "line": r.line + 1, "detail": "%s" % (r.kv,)})
        elif r.tag == "A7AL":
            alloc[r.kv["ch"]] = {"gfc": r.gfc, "player": r.kv["player"], "track": (r.kv["T"] - T_BASE) // T_SIZE, "T": r.kv["T"],
                                 "prio": r.kv["prio"], "line": r.line}
        elif r.tag == "A7PC":
            setup[r.kv["ch"]] = {k: r.kv[k] for k in ("sad", "fmt", "rep", "pnt", "len", "vol", "div", "tmr", "pan")}
            setup[r.kv["ch"]]["gfc"] = r.gfc
        elif r.tag == "A7ST":
            ch = r.kv["ch"]
            a = alloc.pop(ch, None)
            if a is None:
                missing.append({"kind": "start_unallocated", "line": r.line + 1, "detail": "channel %d started with no link" % ch})
            v = {"ch": ch, "alloc": a, "setup": setup.pop(ch, None), "start": {"gfc": r.gfc, "line": r.line, "cnt": r.kv["cnt"],
                 "fields": _cnt(r.kv["cnt"]), "mix": r.kv["mix"], "bias": r.kv["bias"], "status": r.kv["status"]},
                 "updates": [], "ends": [], "gen": sum(1 for u in out if u["ch"] == ch)}
            prev = live.get(ch)
            if prev is not None and not prev["ends"]:
                prev["ends"].append({"kind": "restarted", "gfc": r.gfc, "line": r.line})
            live[ch] = v
            out.append(v)
        elif r.tag in ("A7UT", "A7UV", "A7UP") and r.kv["ch"] in live:
            live[r.kv["ch"]]["updates"].append({"kind": {"A7UT": "timer", "A7UV": "volume", "A7UP": "pan"}[r.tag], "gfc": r.gfc,
                                                "value": r.kv["value"], "div": r.kv.get("div")})
        elif r.tag == "A7SW" and r.kv["ch"] in live and r.kv["old"] >> 31:
            live[r.kv["ch"]]["ends"].append({"kind": "stop_write", "gfc": r.gfc, "line": r.line, "old": r.kv["old"], "new": r.kv["new"]})
        elif r.tag == "A7NE" and r.kv["ch"] in live:
            live[r.kv["ch"]]["ends"].append({"kind": "end_observed", "gfc": r.gfc, "line": r.line})
        elif r.tag == "A7CB" and r.kv["ch"] in live:
            live[r.kv["ch"]]["ends"].append({"kind": "callback", "gfc": r.gfc, "line": r.line, "reason": r.kv["reason"]})
    return {"voices": out, "missing": missing}
